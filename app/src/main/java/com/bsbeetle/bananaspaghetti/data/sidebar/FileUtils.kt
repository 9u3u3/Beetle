package com.bsbeetle.bananaspaghetti.data.sidebar

import androidx.compose.ui.graphics.Color

object FileUtils {
    fun getFileIconColor(fileName: String): Color {
        return when {
            fileName.endsWith(".js") -> Color(0xFFF7DF1E)
            fileName.endsWith(".jsx") -> Color(0xFF61DAFB)
            fileName.endsWith(".ts") -> Color(0xFF3178C6)
            fileName.endsWith(".tsx") -> Color(0xFF007ACC)
            fileName.endsWith(".kt") -> Color(0xFF7F52FF)
            fileName.endsWith(".kts") -> Color(0xFFB57FFF)
            fileName.endsWith(".java") -> Color(0xFFED8B00)
            fileName.endsWith(".c") -> Color(0xFFA8B9CC)
            fileName.endsWith(".cpp") -> Color(0xFF00599C)
            fileName.endsWith(".cs") -> Color(0xFF68217A)
            fileName.endsWith(".swift") -> Color(0xFFFFAC45)
            fileName.endsWith(".go") -> Color(0xFF00ADD8)
            fileName.endsWith(".rs") -> Color(0xFFDEA584)
            fileName.endsWith(".py") -> Color(0xFF3776AB)
            fileName.endsWith(".rb") -> Color(0xFFCC342D)
            fileName.endsWith(".php") -> Color(0xFF777BB4)
            fileName.endsWith(".html") -> Color(0xFFE34C26)
            fileName.endsWith(".xml") -> Color(0xFF8B5CF6)
            fileName.endsWith(".css") -> Color(0xFF2965F1)
            fileName.endsWith(".scss") -> Color(0xFFC6538C)
            fileName.endsWith(".sass") -> Color(0xFFD85888)
            fileName.endsWith(".less") -> Color(0xFF2B4C80)
            fileName.endsWith(".json") -> Color(0xFFFCA311)
            fileName.endsWith(".yaml") || fileName.endsWith(".yml") -> Color(0xFFCB171E)
            fileName.endsWith(".md") -> Color(0xFF42A5F5)
            fileName.endsWith(".txt") -> Color(0xFF9E9E9E)
            fileName.endsWith(".env") -> Color(0xFFEDD652)
            fileName.endsWith(".sh") -> Color(0xFF4EAA25)
            fileName.endsWith(".bat") -> Color(0xFF6A1B9A)
            fileName.endsWith(".sql") -> Color(0xFF00758F)
            fileName.endsWith(".db") || fileName.endsWith(".sqlite") -> Color(0xFF003B57)
            fileName.endsWith(".csv") -> Color(0xFF2E7D32)
            fileName.endsWith(".tsv") -> Color(0xFF388E3C)
            fileName.endsWith(".pdf") -> Color(0xFFDB4437)
            fileName.endsWith(".doc") || fileName.endsWith(".docx") -> Color(0xFF2962FF)
            fileName.endsWith(".xls") || fileName.endsWith(".xlsx") -> Color(0xFF2E7D32)
            fileName.endsWith(".ppt") || fileName.endsWith(".pptx") -> Color(0xFFEA4335)
            fileName.endsWith(".zip") || fileName.endsWith(".rar") -> Color(0xFF795548)
            fileName.endsWith(".tar") || fileName.endsWith(".gz") || fileName.endsWith(".7z") -> Color(0xFF6D4C41)
            fileName.endsWith(".exe") -> Color(0xFF616161)
            fileName.endsWith(".apk") -> Color(0xFF3DDC84)
            fileName.endsWith(".img") || fileName.endsWith(".iso") -> Color(0xFF546E7A)
            fileName.endsWith(".jpg") || fileName.endsWith(".jpeg") -> Color(0xFFFFB300)
            fileName.endsWith(".png") -> Color(0xFF00BCD4)
            fileName.endsWith(".gif") -> Color(0xFFFF4081)
            fileName.endsWith(".svg") -> Color(0xFFFF9800)
            fileName.endsWith(".ico") -> Color(0xFF607D8B)
            fileName.endsWith(".bmp") -> Color(0xFF8BC34A)
            fileName.endsWith(".mp3") || fileName.endsWith(".wav") || fileName.endsWith(".flac") -> Color(0xFF1DB954)
            fileName.endsWith(".mp4") || fileName.endsWith(".mkv") || fileName.endsWith(".mov") || fileName.endsWith(".avi") -> Color(0xFFE53935)
