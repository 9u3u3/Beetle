            fileName.endsWith(".ini") -> Color(0xFF546E7A)
            fileName.endsWith(".log") -> Color(0xFF9E9E9E)
            fileName.endsWith(".conf") -> Color(0xFF607D8B)
            fileName.endsWith(".gradle") -> Color(0xFF02303A)
            fileName.endsWith(".properties") -> Color(0xFF009688)
            fileName.endsWith(".lock") -> Color(0xFF757575)
            fileName.endsWith(".babel") -> Color(0xFFF9DC3E)
            fileName.endsWith(".dockerfile") -> Color(0xFF2496ED)
            fileName.endsWith(".vue") -> Color(0xFF42B883)
            fileName.endsWith(".svelte") -> Color(0xFFFF3E00)
            fileName.endsWith(".astro") -> Color(0xFFFF5A03)
            fileName.endsWith(".dart") -> Color(0xFF00B4AB)
            fileName.endsWith(".lockb") -> Color(0xFF757575)
            fileName.endsWith(".nix") -> Color(0xFF5277C3)
            else -> Color(0xFF858585)
        }
